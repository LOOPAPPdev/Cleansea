/**
 * Extract the CSS custom properties of the vendored Minimal theme into data.
 *   node scripts/minimal-extract.mjs          → writes src/design-system/tokens/minimal.json
 *   node scripts/minimal-extract.mjs --check  → fails if minimal.json is out of date with vendor/
 * Only defaults are kept: declarations on `body`, `body:not(.option)` (option off) and the
 * `.theme-light` / `.theme-dark` groups. Optional feature classes (.minimal-*, .is-mobile …) are skipped.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const vendor = join(root, "vendor/obsidian-minimal");
const out = join(root, "src/design-system/tokens/minimal.json");

const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : f.endsWith(".scss") ? [join(d, f)] : []));

/** Tiny SCSS reader: strips comments, tracks nested selectors, yields [selector, name, value]. */
export function* declarations(src) {
  const text = src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/.*$/gm, "$1");
  const stack = [];
  let buf = "";
  for (const ch of text) {
    if (ch === "{") { stack.push(buf.trim().replace(/\s+/g, " ")); buf = ""; }
    else if (ch === "}") { flush(); stack.pop(); buf = ""; }
    else if (ch === ";") { yield* flush(); buf = ""; }
    else buf += ch;
  }
  function* flush() {
    const m = /^\s*(--[\w-]+)\s*:\s*([\s\S]+?)\s*$/.exec(buf);
    if (m && stack.length) yield [stack.join(" "), m[1], m[2].replace(/\s+/g, " ")];
  }
}

const isDefault = (sel) => sel.split(",").map((s) => s.trim()).some((s) => s === "body" || /^body(:not\([^)]*\))+$/.test(s));
const modeOf = (sel) => {
  const parts = sel.split(",").map((s) => s.trim());
  const light = parts.some((s) => s === ".theme-light" || s === ".theme-light.minimal-default-light");
  const dark = parts.some((s) => s === ".theme-dark" || s === ".theme-dark.minimal-default-dark");
  return light && dark ? "both" : light ? "light" : dark ? "dark" : null;
};

export function extract() {
  const meta = JSON.parse(readFileSync(join(vendor, "VENDOR.json"), "utf8"));
  const res = { $comment: "GENERATED by scripts/minimal-extract.mjs from vendor/obsidian-minimal. Do not edit.", source: meta, defaults: {}, light: {}, dark: {} };
  for (const file of walk(join(vendor, "src/scss")).sort()) {
    const rel = relative(vendor, file);
    if (rel.includes("color-schemes/") || rel.includes("plugins/") || rel.includes("/dev/")) continue; // third-party palettes and plugin skins
    for (const [sel, name, value] of declarations(readFileSync(file, "utf8"))) {
      if (isDefault(sel)) res.defaults[name] ??= { value, file: rel };
      const mode = modeOf(sel);
      if (mode === "light" || mode === "both") res.light[name] ??= { value, file: rel };
      if (mode === "dark" || mode === "both") res.dark[name] ??= { value, file: rel };
    }
  }
  return res;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const json = JSON.stringify(extract(), null, 2) + "\n";
  if (process.argv.includes("--check")) {
    if (readFileSync(out, "utf8") !== json) { console.error("minimal.json is out of date: run npm run minimal"); process.exit(1); }
    console.log("minimal.json is up to date.");
  } else {
    writeFileSync(out, json);
    const r = JSON.parse(json);
    console.log(`minimal.json written: ${Object.keys(r.defaults).length} defaults, ${Object.keys(r.light).length} light, ${Object.keys(r.dark).length} dark (Minimal ${r.source.commit.slice(0, 7)})`);
  }
}
