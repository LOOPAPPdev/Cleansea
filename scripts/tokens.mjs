/**
 * Build design tokens from src/design-system/tokens/tokens.json.
 *   node scripts/tokens.mjs           → writes tokens.css (CSS variables, light + dark)
 *   node scripts/tokens.mjs --check   → fails if any contrast pair is below its minimum
 * The JSON is the source of truth; never edit tokens.css by hand.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src/design-system/tokens");
const t = JSON.parse(readFileSync(join(dir, "tokens.json"), "utf8"));

const resolve = (v) => {
  const m = /^\{([a-z]+)\.([0-9]+)\}$/.exec(v);
  if (!m) return v;
  const out = t.primitives[m[1]]?.[m[2]];
  if (!out) throw new Error(`Unknown token reference ${v}`);
  return out;
};
const theme = (mode) => Object.fromEntries(Object.entries(t.semantic).map(([k, s]) => [k, resolve(s[mode])]));
const light = theme("light");
const dark = theme("dark");

// ---------- contrast (WCAG 2.1) ----------
const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
const lum = (h) => rgb(h).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)).reduce((a, c, i) => a + c * [0.2126, 0.7152, 0.0722][i], 0);
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort(); return (y + 0.05) / (x + 0.05); };

const themes = Object.fromEntries(Object.entries(t.themes ?? {}).map(([k, v]) => [k, Object.fromEntries(Object.entries(v).map(([r, c]) => [r, resolve(c)]))]));

if (process.argv.includes("--check")) {
  let failed = 0;
  for (const [name, th] of Object.entries(themes)) {
    for (const [role, min] of [["text", 4.5], ["accent", 3]]) {
      const r = ratio(th[role], th.ground);
      const ok = r >= min;
      if (!ok) failed++;
      console.log(`${ok ? "✓" : "✗"} theme ${name} ${role} on ground: ${r.toFixed(2)} (min ${min})`);
    }
  }
  for (const [mode, vals] of [["light", light], ["dark", dark]]) {
    for (const [fg, bg, min] of t.contrast) {
      const r = ratio(vals[fg].slice(0, 7), vals[bg].slice(0, 7));
      const ok = r >= min;
      if (!ok) failed++;
      console.log(`${ok ? "✓" : "✗"} ${mode.padEnd(5)} ${fg} on ${bg}: ${r.toFixed(2)} (min ${min})`);
    }
  }
  if (failed) { console.error(`\n${failed} contrast pair(s) below minimum`); process.exit(1); }
  console.log("\nAll contrast pairs pass.");
  process.exit(0);
}

// ---------- CSS ----------
const vars = (o) => Object.entries(o).map(([k, v]) => `  --${k}: ${v};`).join("\n");
const scale = Object.entries(t.scale)
  .flatMap(([group, vals]) => Object.entries(vals).map(([k, v]) => `  --${group}-${k}: ${v};`))
  .join("\n");
const themeCss = Object.entries(themes)
  .map(([k, v]) => `.theme-${k} {\n  --theme-ground: ${v.ground};\n  --theme-text: ${v.text};\n  --theme-accent: ${v.accent};\n}`)
  .join("\n");
const typeCss = Object.entries(t.typography?.steps ?? {})
  .map(([k, v]) => `  --type-size-${k}: ${v.size};\n  --type-leading-${k}: ${v.lineHeight};\n  --type-tracking-${k}: ${v.tracking};`)
  .join("\n");
const css = `/* GENERATED by scripts/tokens.mjs from tokens.json (${t.name} v${t.version}, rule ${t.rule}). Do not edit. */
:root {
${vars(light)}
${scale}
${typeCss}
  color-scheme: light;
}
.dark {
${vars(dark)}
  color-scheme: dark;
}
@media (prefers-color-scheme: dark) {
  :root:not(.light) {
${vars(dark).replace(/^/gm, "  ")}
    color-scheme: dark;
  }
}
/* Themes light / mid / dark: fixed colours for moments of emphasis, independent of page mode. */
${themeCss}
`;
writeFileSync(join(dir, "tokens.css"), css);
console.log(`tokens.css written: ${Object.keys(light).length} semantic colours × 2 modes, ${Object.keys(themes).length} themes, ${Object.keys(t.typography?.steps ?? {}).length} type steps, ${scale.split("\n").length} scale values`);
