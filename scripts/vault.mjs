/**
 * Build the Obsidian vault (src/content/vault/*.md) into a TypeScript module.
 *   node scripts/vault.mjs          → writes src/content/vault.generated.ts
 *   node scripts/vault.mjs --check  → fails if the module is out of date
 * Notes are bundled as data (no filesystem access at runtime on Workers).
 * Frontmatter: title, summary, tags ([a, b]). The file name is the slug and the wikilink target.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src/content/vault");
const out = join(root, "src/content/vault.generated.ts");

function parse(slug, src) {
  const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(src);
  if (!m) throw new Error(`${slug}.md: missing frontmatter`);
  const meta = Object.fromEntries(m[1].split("\n").filter(Boolean).map((l) => {
    const i = l.indexOf(":");
    const k = l.slice(0, i).trim(), v = l.slice(i + 1).trim();
    return [k, /^\[.*\]$/.test(v) ? v.slice(1, -1).split(",").map((x) => x.trim()).filter(Boolean) : v];
  }));
  for (const k of ["title", "summary"]) if (!meta[k]) throw new Error(`${slug}.md: frontmatter needs ${k}`);
  return { slug, title: meta.title, summary: meta.summary, tags: meta.tags ?? [], markdown: m[2].trim() + "\n" };
}

const notes = readdirSync(dir).filter((f) => f.endsWith(".md")).sort().map((f) => parse(f.slice(0, -3), readFileSync(join(dir, f), "utf8")));
const ts = `/* GENERATED by scripts/vault.mjs from src/content/vault/*.md. Do not edit. */
export type VaultNote = { slug: string; title: string; summary: string; tags: string[]; markdown: string };
export const vault: Record<string, VaultNote> = ${JSON.stringify(Object.fromEntries(notes.map((n) => [n.slug, n])), null, 2)};
`;
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== ts) { console.error("vault.generated.ts is out of date: run npm run vault"); process.exit(1); }
  console.log("vault.generated.ts is up to date.");
} else {
  writeFileSync(out, ts);
  console.log(`vault.generated.ts written: ${notes.length} notes`);
}
